// Generates src/Umbraco.Community.Licensing/Format/TextRuleTable.g.cs (ADR-0018): the code points
// outside ASCII a text value may hold, from the Unicode Character Database at a fixed version.
//
//   node tools/unicode/text-rule-table.mjs [--category <path> --core <path>] [--out <path>] [--compare <existing .g.cs>]
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const UNICODE_VERSION = '16.0.0';
export const COMMAND = 'node tools/unicode/text-rule-table.mjs';

const BASE = `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd/`;
export const SOURCES = {
  category: {
    name: 'DerivedGeneralCategory.txt',
    url: `${BASE}extracted/DerivedGeneralCategory.txt`,
    sha256: '7676ab755a41ef82108460238569e60ad65c191ddafe61b36c6765ec1353f293',
  },
  core: {
    name: 'DerivedCoreProperties.txt',
    url: `${BASE}DerivedCoreProperties.txt`,
    sha256: '39d35161f2954497f69e08bdb9e701493f476a3d30222de20028feda36c1dabd',
  },
};

// Letters, combining marks (Mn, Mc), decimal digits and punctuation.
export const ALLOWED_CATEGORIES = [
  'Lu', 'Ll', 'Lt', 'Lm', 'Lo', 'Mn', 'Mc', 'Nd', 'Pc', 'Pd', 'Ps', 'Pe', 'Pi', 'Pf', 'Po',
];
export const IGNORABLE_PROPERTY = 'Default_Ignorable_Code_Point';
const PAIRS_PER_LINE = 4;
const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const DEFAULT_OUT = path.join(REPO_ROOT, 'src', 'Umbraco.Community.Licensing', 'Format', 'TextRuleTable.g.cs');

/** Sort and merge inclusive ranges; adjacent (end + 1 = next start) and overlapping ranges join. */
export function mergeRanges(ranges) {
  const sorted = ranges.map(([s, e]) => [s, e]).sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  const out = [];
  for (const [s, e] of sorted) {
    const last = out[out.length - 1];
    if (last && s <= last[1] + 1) last[1] = Math.max(last[1], e);
    else out.push([s, e]);
  }
  return out;
}

/** Parse a UCD property file into merged ranges for lines whose value is in `values`. */
export function parseUcd(text, values) {
  const wanted = new Set(values);
  const ranges = [];
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.replace(/#.*/, '').trim();
    if (line === '') continue;
    const [cps, value] = line.split(';').map((p) => p.trim());
    if (value === undefined || !wanted.has(value)) continue;
    const m = /^([0-9A-Fa-f]{4,6})(?:\.\.([0-9A-Fa-f]{4,6}))?$/.exec(cps);
    if (!m) throw new Error(`Unrecognised code point field: ${raw}`);
    const start = parseInt(m[1], 16);
    ranges.push([start, m[2] ? parseInt(m[2], 16) : start]);
  }
  return mergeRanges(ranges);
}

/** Remove the code points of `minus` from `ranges`; both sorted and merged. */
export function subtractRanges(ranges, minus) {
  const out = [];
  let j = 0;
  for (const [s0, e] of ranges) {
    let s = s0;
    while (j < minus.length && minus[j][1] < s) j++;
    let k = j;
    while (s <= e && k < minus.length && minus[k][0] <= e) {
      if (minus[k][0] > s) out.push([s, minus[k][0] - 1]);
      s = Math.max(s, minus[k][1] + 1);
      k++;
    }
    if (s <= e) out.push([s, e]);
  }
  return out;
}

export const countCodePoints = (ranges) => ranges.reduce((n, [s, e]) => n + (e - s + 1), 0);

/** Allowed set outside ASCII, with the ignorable code points it removed. */
export function buildAllowed(categoryText, coreText) {
  const categories = parseUcd(categoryText, ALLOWED_CATEGORIES)
    .map(([s, e]) => [Math.max(s, 0x80), e])
    .filter(([s, e]) => s <= e);
  const ignorable = parseUcd(coreText, [IGNORABLE_PROPERTY]);
  const ranges = mergeRanges(subtractRanges(categories, ignorable));
  const removed = mergeRanges(subtractRanges(categories, ranges));
  return { ranges, removed };
}

const hex = (n) => `0x${n.toString(16).toUpperCase().padStart(4, '0')}`;

/** The generated C# file. Same input, same bytes. */
export function emitCSharp(ranges, hashes) {
  const pairs = ranges.map(([s, e]) => `${hex(s)}, ${hex(e)},`);
  const lines = [];
  for (let i = 0; i < pairs.length; i += PAIRS_PER_LINE) {
    lines.push(`        ${pairs.slice(i, i + PAIRS_PER_LINE).join(' ')}`);
  }
  return [
    '// <auto-generated/>',
    `// Generated by: ${COMMAND}`,
    '// Do not edit by hand; regenerate with the command above (ADR-0018).',
    `// Unicode version: ${UNICODE_VERSION}`,
    `// Source: ${SOURCES.category.url}`,
    `//   SHA-256: ${hashes.category}`,
    `// Source: ${SOURCES.core.url}`,
    `//   SHA-256: ${hashes.core}`,
    '// Allowed: general category L, Mn, Mc, Nd or P, less Default_Ignorable_Code_Point; U+0080 and up.',
    '// Ranges are inclusive (start, end) pairs, sorted and merged.',
    '',
    'namespace Umbraco.Community.Licensing;',
    '',
    'internal static partial class TextRuleTable',
    '{',
    `    public const string UnicodeVersion = "${UNICODE_VERSION}";`,
    '',
    '    internal static ReadOnlySpan<int> Ranges => new int[]',
    '    {',
    ...lines,
    '    };',
    '}',
    '',
  ].join('\n');
}

/** Ranges held by an existing generated file. */
export function parseGenerated(text) {
  const start = text.indexOf('new int[]');
  if (start < 0) throw new Error('No range table found in the file.');
  const values = [...text.slice(start).matchAll(/0x([0-9A-Fa-f]+)/g)].map((m) => parseInt(m[1], 16));
  if (values.length % 2 !== 0) throw new Error('The range table has an odd number of values.');
  const ranges = [];
  for (let i = 0; i < values.length; i += 2) ranges.push([values[i], values[i + 1]]);
  return ranges;
}

export const formatRanges = (ranges) => ranges
  .map(([s, e]) => (s === e ? `U+${hex(s).slice(2)}` : `U+${hex(s).slice(2)} to U+${hex(e).slice(2)}`))
  .join(', ');

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');

function parseArgs(argv) {
  const opts = {};
  const known = new Set(['--category', '--core', '--out', '--compare']);
  for (let i = 0; i < argv.length; i += 2) {
    const flag = argv[i];
    if (!known.has(flag)) throw new Error(`Unknown argument: ${flag}`);
    if (argv[i + 1] === undefined) throw new Error(`${flag} needs a value.`);
    opts[flag.slice(2)] = argv[i + 1];
  }
  if (Boolean(opts.category) !== Boolean(opts.core)) {
    throw new Error('--category and --core must be given together.');
  }
  return opts;
}

async function load(source, localPath, fetchFn) {
  let bytes;
  if (localPath) {
    bytes = fs.readFileSync(localPath);
  } else {
    const response = await fetchFn(source.url);
    if (!response.ok) throw new Error(`Download of ${source.name} failed: HTTP ${response.status}`);
    bytes = Buffer.from(await response.arrayBuffer());
  }
  const actual = sha256(bytes);
  if (actual !== source.sha256) {
    throw new Error(`SHA-256 mismatch for ${source.name}: expected ${source.sha256}, got ${actual}. Nothing written.`);
  }
  return { text: bytes.toString('utf8'), hash: actual };
}

/** Run the command. Returns the exit code; never throws for expected failures. */
export async function run(argv, { fetch: fetchFn = globalThis.fetch, log = console.log, error = console.error, sources = SOURCES } = {}) {
  try {
    const opts = parseArgs(argv);
    const category = await load(sources.category, opts.category, fetchFn);
    const core = await load(sources.core, opts.core, fetchFn);
    const { ranges, removed } = buildAllowed(category.text, core.text);

    // Read before writing: the comparison file may be the output file.
    const existing = opts.compare ? parseGenerated(fs.readFileSync(opts.compare, 'utf8')) : null;
    const out = opts.out ?? DEFAULT_OUT;
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, emitCSharp(ranges, { category: category.hash, core: core.hash }));
    log(`Unicode ${UNICODE_VERSION}: ${ranges.length} ranges, ${countCodePoints(ranges)} allowed code points.`);
    log(`${countCodePoints(removed)} code points removed as ignorable by default: ${formatRanges(removed)}`);
    log(`Wrote ${out}`);

    if (existing) {
      const gone = subtractRanges(existing, ranges);
      log(gone.length === 0
        ? `Compared with ${opts.compare}: no code points removed.`
        : `Compared with ${opts.compare}: ${countCodePoints(gone)} code points the new table removes: ${formatRanges(gone)}`);
    }
    return 0;
  } catch (e) {
    error(e.message);
    return 1;
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = await run(process.argv.slice(2));
}
