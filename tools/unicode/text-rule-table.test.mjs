import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {
  buildAllowed, emitCSharp, mergeRanges, parseGenerated, parseUcd, run, DEFAULT_OUT, SOURCES, UNICODE_VERSION,
} from './text-rule-table.mjs';

const temps = [];
after(() => {
  for (const dir of temps) fs.rmSync(dir, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
});
const tempDir = () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'text-rule-table-'));
  temps.push(dir);
  return dir;
};
const sha = (s) => createHash('sha256').update(s).digest('hex');

const CATEGORY = [
  '# DerivedGeneralCategory-16.0.0.txt',
  '',
  '0000..001F    ; Cc # [32] <control-0000>..<control-001F>',
  '0041..005A    ; Lu # [26] LATIN CAPITAL LETTER A..Z',
  '00AA          ; Lo #       FEMININE ORDINAL INDICATOR',
  '00AB          ; Pi #       LEFT-POINTING DOUBLE ANGLE QUOTATION MARK',
  '00AC          ; Sm #       NOT SIGN',
  '0300..034E    ; Mn # [79] COMBINING GRAVE ACCENT..',
  '034F          ; Mn #       COMBINING GRAVE ACCENT',
  '0350..0352    ; Mn # [3]  COMBINING X ABOVE..',
  '3164          ; Lo #       HANGUL FILLER',
  '',
].join('\n');
const CORE = [
  '# DerivedCoreProperties-16.0.0.txt',
  '034F          ; Default_Ignorable_Code_Point # Mn COMBINING GRAPHEME JOINER',
  '3164          ; Default_Ignorable_Code_Point # Lo HANGUL FILLER',
  '0041          ; Alphabetic # Lu',
  '',
].join('\n');
const HASHES = { category: 'a'.repeat(64), core: 'b'.repeat(64) };

test('parse: a range line, a single line, comments and blank lines ignored', () => {
  assert.deepEqual(parseUcd(CATEGORY, ['Lu']), [[0x41, 0x5a]]);
  assert.deepEqual(parseUcd(CATEGORY, ['Lo']), [[0xaa, 0xaa], [0x3164, 0x3164]]);
  assert.deepEqual(parseUcd(CATEGORY, ['Zz']), []);
});

test('parse: only the requested property of a multi-property file', () => {
  assert.deepEqual(parseUcd(CORE, ['Default_Ignorable_Code_Point']), [[0x34f, 0x34f], [0x3164, 0x3164]]);
});

test('merge: adjacent and overlapping ranges join, output sorted', () => {
  assert.deepEqual(mergeRanges([[10, 12], [1, 3], [4, 5], [11, 20], [30, 30]]), [[1, 5], [10, 20], [30, 30]]);
});

test('allowed: an ignorable letter is removed and reported', () => {
  const { ranges, removed } = buildAllowed(CATEGORY, CORE);
  assert.ok(!ranges.some(([s, e]) => s <= 0x3164 && 0x3164 <= e));
  assert.deepEqual(removed, [[0x34f, 0x34f], [0x3164, 0x3164]]);
});

test('allowed: adjacent ranges merged around the removed code point', () => {
  // 00AA and 00AB are Lo and Pi: adjacent, so one range; 0300..034E and 0350..0352 stay split by 034F.
  const { ranges } = buildAllowed(CATEGORY, CORE);
  assert.deepEqual(ranges, [[0xaa, 0xab], [0x300, 0x34e], [0x350, 0x352]]);
});

test('allowed: ASCII excluded, other categories excluded', () => {
  const { ranges } = buildAllowed(CATEGORY, CORE);
  assert.ok(ranges.every(([s]) => s >= 0x80));
  assert.ok(!ranges.some(([s, e]) => s <= 0xac && 0xac <= e)); // Sm
});

test('emit: header, constants, upper-case hex pairs, LF, trailing newline', () => {
  const text = emitCSharp([[0xaa, 0xab], [0x300, 0x34e]], HASHES);
  assert.ok(text.startsWith('// <auto-generated/>\n'));
  assert.match(text, /node tools\/unicode\/text-rule-table\.mjs/);
  assert.ok(text.includes(HASHES.category) && text.includes(HASHES.core));
  assert.ok(text.includes(SOURCES.category.url) && text.includes(SOURCES.core.url));
  assert.ok(text.includes('namespace Umbraco.Community.Licensing;'));
  assert.ok(text.includes('internal static partial class TextRuleTable'));
  assert.ok(text.includes(`public const string UnicodeVersion = "${UNICODE_VERSION}";`));
  assert.ok(text.includes('internal static ReadOnlySpan<int> Ranges => new int[]'));
  assert.ok(text.includes('0x00AA, 0x00AB, 0x0300, 0x034E,'));
  assert.ok(!text.includes('\r'));
  assert.ok(text.endsWith('}\n'));
});

test('emit: a fixed number of pairs per line', () => {
  const ranges = Array.from({ length: 9 }, (_, i) => [0x100 + i * 4, 0x100 + i * 4]);
  const rows = emitCSharp(ranges, HASHES).split('\n').filter((l) => /^ {8}0x/.test(l));
  assert.deepEqual(rows.map((r) => (r.match(/0x/g) ?? []).length / 2), [4, 4, 1]);
});

test('emit: byte-identical output for the same input', () => {
  const a = buildAllowed(CATEGORY, CORE).ranges;
  const b = buildAllowed(CATEGORY, CORE).ranges;
  assert.equal(emitCSharp(a, HASHES), emitCSharp(b, HASHES));
});

test('generated file parses back to the same ranges', () => {
  const { ranges } = buildAllowed(CATEGORY, CORE);
  assert.deepEqual(parseGenerated(emitCSharp(ranges, HASHES)), ranges);
});

test('default output is under the repository root, independent of the cwd', () => {
  assert.ok(path.isAbsolute(DEFAULT_OUT));
  assert.ok(DEFAULT_OUT.endsWith(path.join('src', 'Umbraco.Community.Licensing', 'Format', 'TextRuleTable.g.cs')));
});

// ---- command ----

const testSources = (category, core) => ({
  category: { ...SOURCES.category, sha256: sha(category) },
  core: { ...SOURCES.core, sha256: sha(core) },
});
const fakeFetch = (files) => async (url) => {
  const body = files[url];
  if (body === undefined) return { ok: false, status: 404 };
  return { ok: true, status: 200, arrayBuffer: async () => Buffer.from(body) };
};
const quiet = () => {
  const lines = [];
  return { lines, log: (m) => lines.push(m), error: (m) => lines.push(`ERROR ${m}`) };
};

test('command: hash match downloads and writes the file', async () => {
  const out = path.join(tempDir(), 'T.g.cs');
  const io = quiet();
  const sources = testSources(CATEGORY, CORE);
  const fetch = fakeFetch({ [SOURCES.category.url]: CATEGORY, [SOURCES.core.url]: CORE });
  const code = await run(['--out', out], { fetch, sources, log: io.log, error: io.error });
  assert.equal(code, 0);
  assert.deepEqual(parseGenerated(fs.readFileSync(out, 'utf8')), [[0xaa, 0xab], [0x300, 0x34e], [0x350, 0x352]]);
  assert.ok(io.lines.some((l) => l.includes('3 ranges')));
  assert.ok(io.lines.some((l) => l.includes('2 code points removed')));
});

test('command: hash mismatch refuses, names the file, writes nothing', async () => {
  const out = path.join(tempDir(), 'T.g.cs');
  const io = quiet();
  const sources = testSources(CATEGORY, CORE);
  const fetch = fakeFetch({ [SOURCES.category.url]: CATEGORY, [SOURCES.core.url]: `${CORE}# changed\n` });
  const code = await run(['--out', out], { fetch, sources, log: io.log, error: io.error });
  assert.equal(code, 1);
  assert.ok(io.lines.some((l) => l.includes('ERROR') && l.includes(SOURCES.core.name) && l.includes('mismatch')));
  assert.ok(!fs.existsSync(out));
});

test('command: paths given as arguments are read and hash-checked, no fetch', async () => {
  const dir = tempDir();
  const cat = path.join(dir, 'cat.txt');
  const core = path.join(dir, 'core.txt');
  const out = path.join(dir, 'T.g.cs');
  fs.writeFileSync(cat, CATEGORY);
  fs.writeFileSync(core, CORE);
  const sources = testSources(CATEGORY, CORE);
  const fetch = async () => { throw new Error('network used'); };
  const io = quiet();
  assert.equal(await run(['--category', cat, '--core', core, '--out', out], { fetch, sources, log: io.log, error: io.error }), 0);
  assert.ok(fs.existsSync(out));

  fs.writeFileSync(core, `${CORE}# edited\n`);
  const out2 = path.join(dir, 'T2.g.cs');
  assert.equal(await run(['--category', cat, '--core', core, '--out', out2], { fetch, sources, log: io.log, error: io.error }), 1);
  assert.ok(!fs.existsSync(out2));
});

test('command: --compare lists a removed range, and none when nothing is removed', async () => {
  const dir = tempDir();
  const old = path.join(dir, 'old.g.cs');
  fs.writeFileSync(old, emitCSharp([[0xaa, 0xab], [0x300, 0x352], [0x1000, 0x1002]], HASHES));
  const sources = testSources(CATEGORY, CORE);
  const fetch = fakeFetch({ [SOURCES.category.url]: CATEGORY, [SOURCES.core.url]: CORE });
  const io = quiet();
  await run(['--out', path.join(dir, 'n.g.cs'), '--compare', old], { fetch, sources, log: io.log, error: io.error });
  const line = io.lines.find((l) => l.startsWith('Compared'));
  assert.ok(line.includes('U+034F'));
  assert.ok(line.includes('U+1000 to U+1002'));
  assert.ok(!line.includes('U+0300'));

  const same = path.join(dir, 'same.g.cs');
  fs.writeFileSync(same, emitCSharp([[0xaa, 0xab]], HASHES));
  const io2 = quiet();
  await run(['--out', path.join(dir, 'n2.g.cs'), '--compare', same], { fetch, sources, log: io2.log, error: io2.error });
  assert.ok(io2.lines.some((l) => l.startsWith('Compared') && l.includes('no code points removed')));
});

test('command: bad arguments exit non-zero', async () => {
  const io = quiet();
  assert.equal(await run(['--bogus', 'x'], { log: io.log, error: io.error }), 1);
  assert.equal(await run(['--category', 'x'], { log: io.log, error: io.error }), 1);
});
